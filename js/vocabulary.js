const VOWEL = /^[aeiouyàâäéèêëîïôöùûü]/i;

/** Whether the article runs into the word: l’eau, l’homme — but le hasard. */
const elides = (word) => VOWEL.test(word) || (word.startsWith('h') && !ASPIRATED.has(word));

/**
 * The French side of the card. A noun is never shown bare: it arrives with
 * its article, because that is the half people fail to learn. Where the
 * article elides and hides the gender — l’eau could be either — the gender
 * is spelt out instead.
 */
function shown(word, kind, extra) {
  if (kind === 'a') return extra ? `${word} (${extra})` : word;
  if (kind !== 'n') return word;
  if (extra.endsWith('-pl')) return `les ${word} (${extra[0]} pl)`;
  if (extra === 'mf') return elides(word) ? `l’${word} (m/f)` : `le/la ${word}`;
  if (elides(word)) return `l’${word} (${extra})`;
  return `${extra === 'm' ? 'le' : 'la'} ${word}`;
}

/**
 * What counts as having produced the word. For a noun that means an article
 * that proves you know the gender, which is why l’eau is not on this list:
 * it is what you would write, but it says nothing about which one it is.
 */
function accepts(word, kind, extra) {
  if (kind === 'a') return extra ? [word, extra] : [word];
  if (kind !== 'n') return [word];
  if (extra.endsWith('-pl')) return [`les ${word}`, `des ${word}`];
  // Before a vowel the definite article elides and stops proving anything —
  // l'eau could be either — so those words are only answered with un or une.
  if (elides(word)) {
    if (extra === 'mf') return [`un ${word}`, `une ${word}`];
    return [`${extra === 'm' ? 'un' : 'une'} ${word}`];
  }
  if (extra === 'mf') return ['le', 'la', 'un', 'une'].map((a) => `${a} ${word}`);
  return extra === 'm' ? [`le ${word}`, `un ${word}`] : [`la ${word}`, `une ${word}`];
}

const slug = (value) => value.normalize('NFD').replace(/[̀-ͯ]/g, '')
  .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const bandOf = (rank) => BANDS.find((band) => rank >= band.from && rank < band.to).id;

export const WORDS = RAW.map(([word, en, kind, extra], rank) => ({
  word,
  en,
  kind,
  rank,
  band: bandOf(rank),
  gender: kind === 'n' ? extra : null,
  feminine: kind === 'a' ? (extra ?? word) : null,
  shown: shown(word, kind, extra),
  accepts: accepts(word, kind, extra),
  // The id carries the kind, so a word that is both can be both: le sourire
  // and sourire are two cards.
  id: `${slug(word)}-${kind}`,
}));

export const WORD_BY_ID = new Map(WORDS.map((entry) => [entry.id, entry]));

export const wordsFor = (bands, kinds) =>
  WORDS.filter((entry) => bands.includes(entry.band) && kinds.includes(entry.kind));
