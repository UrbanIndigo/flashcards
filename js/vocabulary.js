/**
 * A thousand French words, with their genders.
 *
 * The sentences deck teaches words by meeting them in use. This one is the
 * blunt instrument: the word, what it means, and — the part that actually
 * costs marks — whether it is *le* or *la*.
 *
 * Gender is not decoration here. A noun learnt without its article is a
 * noun half learnt, so the French side of every noun card carries the
 * article, and typing the bare word is marked as a near miss rather than
 * waved through. Adjectives carry their feminine in brackets where it
 * differs: grand (grande), heureux (heureuse), and nothing after rouge,
 * which does not change.
 *
 * Each row is [word, meaning, kind, extra]:
 *
 *   'n'  a noun      — extra is 'm', 'f', 'mf' for either, 'f-pl' for a
 *                      noun that only exists in the plural
 *   'a'  an adjective — extra is the feminine form, or absent when the word
 *                      is the same in both
 *   'v'  a verb       — the infinitive, no extra
 *   'x'  everything else: adverbs, prepositions, conjunctions
 *
 * The articles le/la/un/une are not in the list. A card whose answer is
 * "the" teaches nothing, and they turn up in every other card anyway.
 */

