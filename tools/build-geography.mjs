/**
 * Builds js/subjects/geography-data.js.
 *
 *   node tools/build-geography.mjs > js/subjects/geography-data.js
 *
 * Names and ISO codes come from `country-list` (MIT), capitals from
 * `countries-list` (MIT), flag artwork from `flag-icons` (MIT; the flags
 * themselves are public symbols). The regional grouping is ordinary
 * geography, and the aliases are what someone might reasonably type.
 */

import { readFileSync, existsSync, writeFileSync } from 'node:fs';
import { COUNTRIES } from './countries.js';

const capitals = JSON.parse(readFileSync('/tmp/cl/package/countries.min.json', 'utf8'));

/**
 * Countries with more than one capital, or whose capital moved. Marking a
 * defensible answer wrong teaches nothing, so all of these are accepted.
 */
const ALSO = {
  ZA: ['Cape Town', 'Bloemfontein'],      // executive, legislative, judicial
  BO: ['La Paz'],                          // seat of government
  NL: ['The Hague', 'Den Haag'],           // seat of government
  CI: ['Abidjan'],                         // economic capital
  TZ: ['Dar es Salaam'],                   // former capital
  LK: ['Sri Jayawardenepura Kotte', 'Kotte'],
  MM: ['Nay Pyi Taw', 'Yangon', 'Rangoon'],
  BJ: ['Cotonou'],                         // seat of government
  SZ: ['Mbabane'],                         // administrative capital
  IL: ['Tel Aviv'],
  KZ: ['Nur-Sultan'],                      // the name it held 2019-2022
  MY: ['Putrajaya'],                       // administrative capital
  US: ['Washington', 'Washington DC'],
  BI: ['Bujumbura'],                       // economic capital
};

const missing = [];
const countries = COUNTRIES.map((country) => {
  const capital = capitals[country.code]?.capital;
  const file = ['svg', 'webp'].map((ext) => `${country.code.toLowerCase()}.${ext}`)
    .find((name) => existsSync(new URL(`../flags/${name}`, import.meta.url)));
  if (!capital) missing.push(`${country.code} capital`);
  if (!file) missing.push(`${country.code} flag`);
  return {
    ...country,
    capital,
    flag: file,
    ...(ALSO[country.code] ? { capitalAka: ALSO[country.code] } : {}),
  };
});

if (missing.length) {
  process.stderr.write(`MISSING: ${missing.join(', ')}\n`);
  process.exit(1);
}
const strays = Object.keys(ALSO).filter((c) => !COUNTRIES.some((x) => x.code === c));
if (strays.length) {
  process.stderr.write(`ALIASES FOR UNKNOWN CODES: ${strays.join(', ')}\n`);
  process.exit(1);
}

process.stderr.write(`${countries.length} countries, ${countries.filter((c) => c.flag.endsWith('.webp')).length} raster flags\n`);

// The service worker precaches the flags but cannot import an ES module, so
// it reads this list at install time instead of having 196 paths pasted in.
writeFileSync(
  new URL('../flags/manifest.json', import.meta.url),
  `${JSON.stringify(countries.map((c) => c.flag))}\n`,
);

process.stdout.write(`/**
 * Countries: name, region, capital and flag artwork.
 *
 * Generated by tools/build-geography.mjs — do not edit by hand.
 *
 * Names and ISO 3166-1 codes from \`country-list\` (MIT, (c) 2016 Fannar Snær
 * Harðarson); capitals from \`countries-list\` (MIT); flag artwork from
 * \`flag-icons\` (MIT). Flags are SVG where the design is geometric, and WebP
 * at display resolution where it is an illustrated coat of arms — which
 * takes the set from 1.9MB to about 510KB without a visible difference.
 *
 * \`aka\` and \`capitalAka\` are alternative answers that are accepted:
 * everyday names, former names, and the several capitals that some countries
 * genuinely have.
 */

export const COUNTRIES = ${JSON.stringify(countries, null, 0)
  .replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')};

export const REGIONS = ${JSON.stringify([...new Set(countries.map((c) => c.region))], null, 2)};
`);
